# VERIFICATION
# ==============================================================================


@dataclass(frozen=True, slots=True)
class Report:
    """What verification found."""

    uncovered: tuple[str, ...] = ()
    missing_targets: tuple[tuple[str, str], ...] = ()
    unexplained: tuple[str, ...] = ()
    orphans: tuple[str, ...] = ()

    @property
    def ok(self) -> bool:
        return not (
            self.uncovered or self.missing_targets or self.unexplained or self.orphans
        )

    def describe(self) -> str:
        if self.ok:
            return "placement: every empty directory is covered and every target exists"
        parts: list[str] = []
        if self.uncovered:
            parts.append(
                f"{len(self.uncovered)} directory(ies) not covered by the table: "
                + ", ".join(self.uncovered[:5])
            )
        if self.missing_targets:
            parts.append(
                f"{len(self.missing_targets)} pointer(s) name a path that does not "
                "exist: " + ", ".join(f"{d} -> {t}" for d, t in self.missing_targets[:5])
            )
        if self.unexplained:
            parts.append(
                f"{len(self.unexplained)} planned directory(ies) with no reason: "
                + ", ".join(self.unexplained[:5])
            )
        if self.orphans:
            parts.append(
                f"{len(self.orphans)} generated README(s) describe a directory that "
                "now holds code: " + ", ".join(self.orphans[:5])
            )
        return "; ".join(parts)


def verify(root: Path | None = None) -> Report:
    """
    Check the table against the tree.

    Four failures matter, and two of them are the same failure seen from
    opposite ends: a pointer whose target was renamed, and a note left behind
    in a directory that has since been built. Both are READMEs that lie, and
    without this check nothing would ever notice either one.
    """
    base = root or ROOT
    reasons = planned_reasons()

    uncovered: list[str] = []
    missing: list[tuple[str, str]] = []
    unexplained: list[str] = []

    for directory in empty_directories(base):
        path = relative(directory, base)
        entry = resolve(path)

        if entry is None:
            uncovered.append(path)
            continue

        if entry.state is State.IMPLEMENTED:
            if not entry.target:
                missing.append((path, "<no target declared>"))
            elif not (base / entry.target).exists():
                missing.append((path, entry.target))

        if entry.state is State.PLANNED:
            name = path.rsplit("/", 1)[-1]
            if not entry.note and not reasons.get(name):
                unexplained.append(path)

    return Report(
        uncovered=tuple(uncovered),
        missing_targets=tuple(missing),
        unexplained=tuple(unexplained),
        orphans=tuple(relative(p, base) for p in generated_orphans(base)),
    )


def main(argv: Iterable[str] | None = None) -> int:
    """`python -m tools.placement [--write]`."""
    import sys

    args = list(argv if argv is not None else sys.argv[1:])
    write = "--write" in args

    report = verify()
    print(report.describe())

    produced = generate(write=write)
    verb = "wrote" if write else "would write"
    print(f"{verb} {len(produced)} README(s)")

    # An orphan is removed rather than rewritten: the table has no entry for a
    # directory that holds code, so there is nothing to regenerate it from.
    orphans = generated_orphans()
    if orphans:
        removed = "removed" if write else "would remove"
        print(f"{removed} {len(orphans)} orphaned README(s)")
        if write:
            for readme in orphans:
                readme.unlink()

    if not write:
        print("re-run with --write to apply")

    return 0 if (report.ok or write) else 1


if __name__ == "__main__":
    raise SystemExit(main())


