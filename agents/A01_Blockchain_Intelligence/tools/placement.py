# PLANNED REASONS
# ==============================================================================


def planned_reasons() -> dict[str, str]:
    """
    Why each unbuilt skill is unbuilt, from the registry that already says so.

    Imported lazily: this module must stay runnable when the package tree is
    mid-edit, which is exactly when someone regenerates placement.
    """
    try:
        from skills.registry import PLANNED_SKILLS

        return dict(PLANNED_SKILLS)
    except Exception:  # noqa: BLE001 - tooling must survive a broken import
        return {}


# ==============================================================================
# GENERATION
# ==============================================================================


def render(relative_path: str, entry: Placement, reasons: dict[str, str]) -> str:
    """The README for one directory."""
    name = relative_path.rsplit("/", 1)[-1]
    lines = [GENERATED_MARKER, "", f"# `{relative_path}/`", ""]

    if entry.state is State.NEVER:
        lines += [
            "**Deliberately empty. Do not add code here.**",
            "",
            entry.note,
            "",
        ]
    elif entry.state is State.IMPLEMENTED:
        note = entry.note or "This concept is implemented elsewhere."
        lines += [
            f"**Implemented at [`{entry.target}`]({_link(relative_path, entry.target)}).**",
            "",
            note,
            "",
            "Do not add code here. A second implementation under this name would",
            "drift from the first, and nothing would report the divergence — see",
            "`docs/architecture/folder-architecture.md` §11.",
            "",
        ]
    else:
        reason = entry.note or reasons.get(name, "")
        lines += [
            "**Not built yet.**",
            "",
            (
                f"Blocked by: {reason}"
                if reason
                else "No implementation, and no blocking reason recorded."
            ),
            "",
            "The directory is kept because the structure is the roadmap. It will",
            "hold code once the capability above exists — not before, because a",
            "module that cannot do what its name claims is worse than an absence.",
            "",
        ]

    lines += [
        "---",
        "",
        "Regenerate with `python -m tools.placement --write`.",
        "",
    ]
    return "\n".join(lines)


def _link(from_dir: str, target: str) -> str:
    """A relative markdown link from the empty directory to its target."""
    depth = from_dir.count("/") + 1
    return "../" * depth + target


def generate(root: Path | None = None, *, write: bool = False) -> dict[str, str]:
    """
    Build a README for every empty directory.

    Returns the mapping of path to content. With ``write`` false nothing is
    touched, which is what the test uses to compare intent against the tree.
    """
    base = root or ROOT
    reasons = planned_reasons()
    produced: dict[str, str] = {}

    for directory in empty_directories(base):
        path = relative(directory, base)
        entry = resolve(path)
        if entry is None:
            continue
        content = render(path, entry, reasons)
        produced[path] = content
        if write:
            (directory / "README.md").write_text(content, encoding="utf-8")

    return produced


