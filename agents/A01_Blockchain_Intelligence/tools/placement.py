"""
CIE-OS
A01 Blockchain Intelligence Agent

Module:
    tools.placement

Purpose:
    Say, for every directory that holds no code, where that concept is actually
    implemented -- or what its implementation is waiting on.

Design goals:
    - One table; the 143 READMEs are generated, never hand-maintained
    - Every pointer's target verified to exist, so a rename fails a test
    - `planned` reasons sourced from the registry that already holds them
    - Deterministic output; regenerating an unchanged tree changes nothing
    - No package imports at module load, so this stays runnable in a broken tree

Notes:
    A01's scaffolding names concepts it has not built, and names several it
    *has* built in a second place. ``blockchain/decoding/events/`` is empty
    because event decoding lives in ``contracts/``; ``api/`` is empty because
    the HTTP surface is ``interfaces/rest.py``. Both are correct. What is not
    correct is leaving the empty directory unexplained --
    ``docs/architecture/folder-architecture.md`` §10 puts it exactly:

        "an empty directory named ``security/`` invites code to be written in
        the wrong place."

    So each empty directory gets a short README naming its canonical home. The
    alternative the architecture doc recommends -- deleting them -- also works,
    but loses the roadmap the tree encodes, and the operator wants that kept.

    **The pointers are generated, and that is the point.** 143 hand-written
    notes would be 143 future lies: the first rename makes one wrong, and
    nothing catches it. Here the table is the single source, and
    :func:`verify` asserts every target still exists -- so a rename breaks a
    test instead of quietly stranding a reader.

    ``planned`` reasons are read from :data:`skills.registry.PLANNED_SKILLS`
    rather than restated. Two lists of "why this is not built yet" drift, and
    the drift is invisible.
"""

from __future__ import annotations

import fnmatch

from dataclasses import dataclass
from enum import StrEnum
from pathlib import Path
from typing import Final, Iterable

#: Repository root, derived from this file rather than assumed. The agent is
#: checked out at different depths in different layouts.
ROOT: Final[Path] = Path(__file__).resolve().parent.parent

#: Marker on every generated file, so a human edit is distinguishable and a
#: regeneration knows what it may overwrite.
GENERATED_MARKER: Final[str] = "<!-- generated by tools/placement.py -->"

#: Directories that are not part of the agent and are never scanned.
SKIP_PARTS: Final[frozenset[str]] = frozenset(
    {"__pycache__", ".git", ".pytest_cache", ".venv", "node_modules", "data", "logs"}
)


class State(StrEnum):
    """Why a directory is empty."""

    #: The concept is built, at a different path. Do not write it here.
    IMPLEMENTED = "implemented"
    #: Not built. The reason is a missing capability, named.
    PLANNED = "planned"
    #: Deliberately empty, and must stay that way.
    NEVER = "never"


@dataclass(frozen=True, slots=True)
class Placement:
    """One rule covering a directory or a glob of them."""

    pattern: str
    state: State
    #: Repo-relative path of the real implementation. Required for IMPLEMENTED,
    #: verified to exist.
    target: str = ""
    #: One line: what this slot is for, and why it is where it is.
    note: str = ""

    def matches(self, relative: str) -> bool:
        return fnmatch.fnmatch(relative, self.pattern)


